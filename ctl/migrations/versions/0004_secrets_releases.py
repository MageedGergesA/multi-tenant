"""Envelope secrets and release manifests (DOC-03 §2.2, §2.7; ADR-006; DOC-05 §4).

Per-tenant secrets are generated by ctl-1 and stored age-encrypted to the
dispatcher's key; region secrets (B2 write key, operational restore key) are
uploaded already encrypted. Only `ctl_dispatcher` can read `secret_ref`; the
operator API runs as `ctl_app`, which can add secrets but never read them.
"""
from alembic import op

revision = '0004'
down_revision = '0003'

SQL = """
CREATE TABLE secret_ref (
    id uuid PRIMARY KEY,
    kind text NOT NULL CHECK (kind IN ('db_password', 'admin_passwd', 'smtp', 'tenant_salt', 'tenant_admin_password',
                                       'b2_write_key', 'region_restore_key')),
    scope_tenant_id uuid REFERENCES tenant(id),
    ciphertext bytea NOT NULL,                 -- age, to the dispatcher's recipient
    created_at timestamptz NOT NULL,
    rotated_at timestamptz,
    state text NOT NULL DEFAULT 'active' CHECK (state IN ('active', 'rotating', 'revoked'))
);

CREATE TABLE region (
    id uuid PRIMARY KEY,
    code text UNIQUE NOT NULL,
    backup_recipient text NOT NULL,            -- age X25519 public key: backups are encrypted to it
    b2_write_key_ref uuid REFERENCES secret_ref(id),
    restore_key_ref uuid REFERENCES secret_ref(id),
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'retired'))
);
ALTER TABLE host
    ADD COLUMN region_id uuid REFERENCES region(id),
    ADD COLUMN age_recipient text;             -- the agent's X25519 key for envelope secrets (Host.Enroll)

-- Which secret an environment uses for each purpose (DOC-03 keeps these on
-- db_binding, runtime_slot and mail_identity, which Tenant.Create will write).
CREATE TABLE secret_binding (
    environment_id uuid NOT NULL REFERENCES environment(id),
    purpose text NOT NULL CHECK (purpose IN ('db_password', 'admin_passwd', 'smtp', 'tenant_salt',
                                             'tenant_admin_password')),
    secret_ref_id uuid NOT NULL REFERENCES secret_ref(id),
    PRIMARY KEY (environment_id, purpose)
);

CREATE TABLE release_cell (
    id uuid PRIMARY KEY,
    cell text UNIQUE NOT NULL,                 -- community/19.0/ubuntu-24.04/py3.12/pg16
    edition text NOT NULL CHECK (edition = 'community'),       -- INV-5
    odoo_major text NOT NULL,
    status text NOT NULL CHECK (status IN ('candidate', 'available', 'deprecated', 'withdrawn'))
);

-- [AO]
CREATE TABLE evidence_artifact (
    id uuid PRIMARY KEY,
    kind text NOT NULL CHECK (kind IN ('release_approval', 'test_result', 'restore_drill', 'approval', 'security_scan')),
    subject_digest text,                       -- the image digest the evidence is about (INV-6)
    uri text NOT NULL,
    sha256 text NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    produced_by uuid REFERENCES operator(id),
    produced_at timestamptz NOT NULL
);
CREATE TRIGGER evidence_artifact_ao BEFORE UPDATE OR DELETE ON evidence_artifact
    FOR EACH ROW EXECUTE FUNCTION reject_change();

CREATE TABLE image_release (
    id uuid PRIMARY KEY,
    release_cell_id uuid NOT NULL REFERENCES release_cell(id),
    image_digest text UNIQUE NOT NULL,
    change_class text NOT NULL CHECK (change_class IN ('patch', 'module_update', 'major')),
    addon_manifest_sha256 text NOT NULL,
    module_versions jsonb NOT NULL,
    manifest jsonb NOT NULL,                   -- as signed with the release key; sent in envelopes verbatim
    status text NOT NULL CHECK (status IN ('built', 'evidence_pending', 'approved', 'revoked')),
    approval_evidence_id uuid REFERENCES evidence_artifact(id),
    created_at timestamptz NOT NULL,
    CHECK (status <> 'approved' OR approval_evidence_id IS NOT NULL)          -- INV-6
);

ALTER TABLE tenant ADD COLUMN release_cell_id uuid REFERENCES release_cell(id);
ALTER TABLE environment
    ADD COLUMN image_release_id uuid REFERENCES image_release(id),
    ADD COLUMN source_backup_id uuid REFERENCES backup_point(id),
    ADD COLUMN expires_at timestamptz;
ALTER TABLE operation ADD COLUMN image_release_id uuid REFERENCES image_release(id);

DO $$ BEGIN
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'ctl_dispatcher') THEN
        CREATE ROLE ctl_dispatcher NOLOGIN;
    END IF;
END $$;
GRANT ctl_app TO ctl_dispatcher;
GRANT INSERT ON secret_ref, secret_binding, evidence_artifact TO ctl_app;
GRANT SELECT ON secret_binding, region, release_cell, image_release, evidence_artifact TO ctl_app;
GRANT INSERT, UPDATE (status, approval_evidence_id) ON image_release TO ctl_app;
GRANT UPDATE (b2_write_key_ref, restore_key_ref) ON region TO ctl_app;
-- ctl_app sees what secrets exist, never their ciphertext.
GRANT SELECT (id, kind, scope_tenant_id, created_at, rotated_at, state) ON secret_ref TO ctl_app;
GRANT UPDATE (state, rotated_at) ON secret_ref TO ctl_app;
GRANT SELECT ON secret_ref TO ctl_dispatcher;
"""


def upgrade():
    op.execute(SQL)
